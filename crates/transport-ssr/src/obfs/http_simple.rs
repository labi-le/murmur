#[cfg(test)]
mod tests {
    use std::net::{IpAddr, Ipv4Addr, SocketAddr};

    use super::*;

    struct DuplexConn(tokio::io::DuplexStream);

    impl AsyncRead for DuplexConn {
        fn poll_read(self: Pin<&mut Self>, cx: &mut Context<'_>, buf: &mut ReadBuf<'_>) -> Poll<io::Result<()>> {
            Pin::new(&mut self.get_mut().0).poll_read(cx, buf)
        }
    }

    impl AsyncWrite for DuplexConn {
        fn poll_write(self: Pin<&mut Self>, cx: &mut Context<'_>, buf: &[u8]) -> Poll<io::Result<usize>> {
            Pin::new(&mut self.get_mut().0).poll_write(cx, buf)
        }

        fn poll_flush(self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<io::Result<()>> {
            Pin::new(&mut self.get_mut().0).poll_flush(cx)
        }

        fn poll_shutdown(self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<io::Result<()>> {
            Pin::new(&mut self.get_mut().0).poll_shutdown(cx)
        }
    }

    impl Stream for DuplexConn {
        fn local_addr(&self) -> io::Result<SocketAddr> {
            Ok(SocketAddr::new(IpAddr::V4(Ipv4Addr::LOCALHOST), 0))
        }

        fn peer_addr(&self) -> io::Result<SocketAddr> {
            Ok(SocketAddr::new(IpAddr::V4(Ipv4Addr::LOCALHOST), 0))
        }
    }

    /// The head is random (user agent and head-data split both drawn at random) unless a `Param`
    /// carrying a `#` supplies a literal body and there is one host, so the two-byte payload below
    /// stays under the `bLength-headLength>64` split threshold and the head is fixed.
    #[tokio::test]
    async fn build_head_from_param_body_is_deterministic() {
        let (client, _server) = tokio::io::duplex(256);
        let base = Base {
            host: "ignored.example".to_owned(),
            port: 80,
            key: b"0123456789abcdef".to_vec(),
            iv_size: 16,
            param: "example.com#hello".to_owned(),
        };
        let conn = HttpConn {
            conn: Box::new(DuplexConn(client)),
            obfs: HttpObfs { base, post: false },
            has_sent_header: false,
            has_recv_header: false,
            buf: Vec::new(),
            pending: None,
            pending_written: 0,
        };

        let head = conn.build_head(b"hi");
        assert_eq!(hex::encode(&head), hex::encode(b"GET /%68%69 HTTP/1.1\r\nHost: example.com\r\nhello\r\n\r\n"));
    }
}
