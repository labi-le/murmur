/// `init()`, called from the registry's initializer instead of at package load.
pub(crate) fn init(list: &mut ObfsList) {
    register(list, "http_simple", new_http_simple, 0);
}
#[derive(Clone, Debug)]
pub(crate) struct HttpObfs {
    pub(crate) base: Base,
    pub(crate) post: bool,
}

pub(crate) fn new_http_simple(b: &Base) -> Box<dyn Obfs> {
    Box::new(HttpObfs { base: b.clone(), post: false })
}
pub(crate) struct HttpConn {
    conn: Box<dyn Stream>,
    obfs: HttpObfs,
    has_sent_header: bool,
    has_recv_header: bool,
    buf: Vec<u8>,
    /// The request head and its payload, kept until the connector has accepted all of it.
    pending: Option<BytesMut>,
    pending_written: usize,
}

impl Obfs for HttpObfs {
    fn stream_conn(&self, c: Box<dyn Stream>) -> Box<dyn Stream> {
        Box::new(HttpConn {
            conn: c,
            obfs: self.clone(),
            has_sent_header: false,
            has_recv_header: false,
            buf: Vec::new(),
            pending: None,
            pending_written: 0,
        })
    }
}

impl HttpConn {
    /// `Write`'s request, with the head data smuggled into the request line.
    fn build_head(&self, b: &[u8]) -> BytesMut {
        // 30: head length
        let head_length = usize::try_from(self.obfs.base.iv_size + 30).unwrap_or(0);

        let head_data_length =
            if b.len() > head_length + 64 { head_length + rand::rng().random_range(0..65) } else { b.len() };
        let head_data = b.get(..head_data_length).unwrap_or_default();
        let rest = b.get(head_data_length..).unwrap_or_default();

        let mut body = String::new();
        let mut host = self.obfs.base.host.clone();
        if !self.obfs.base.param.is_empty() {
            match self.obfs.base.param.find('#') {
                Some(pos) => {
                    let (head, tail) = self.obfs.base.param.split_at(pos);
                    body = tail.get(1..).unwrap_or_default().replace('\n', "\r\n");
                    body = body.replace("\\n", "\r\n");
                    head.clone_into(&mut host);
                }
                None => host.clone_from(&self.obfs.base.param),
            }
        }
        let hosts: Vec<&str> = host.split(',').collect();
        let host = hosts.get(rand::rng().random_range(0..hosts.len())).copied().unwrap_or_default();

        let mut buf = pool::get_buffer();
        if self.obfs.post {
            buf.put_slice(b"POST /");
        } else {
            buf.put_slice(b"GET /");
        }
        pack_url_encoded_head_data(&mut buf, head_data);
        buf.put_slice(b" HTTP/1.1\r\nHost: ");
        buf.put_slice(host.as_bytes());
        if self.obfs.base.port != 80 {
            buf.put_slice(b":");
            buf.put_slice(self.obfs.base.port.to_string().as_bytes());
        }
        buf.put_slice(b"\r\n");
        if body.is_empty() {
            buf.put_slice(b"User-Agent: ");
            let agent = USER_AGENT.get(rand::rng().random_range(0..USER_AGENT.len())).copied().unwrap_or_default();
            buf.put_slice(agent.as_bytes());
            buf.put_slice(
                b"\r\nAccept: text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8\r\nAccept-Language: en-US,en;q=0.8\r\nAccept-Encoding: gzip, deflate\r\n",
            );
            if self.obfs.post {
                pack_boundary(&mut buf);
            }
            buf.put_slice(b"DNT: 1\r\nConnection: keep-alive\r\n\r\n");
        } else {
            buf.put_slice(body.as_bytes());
            buf.put_slice(b"\r\n\r\n");
        }
        buf.put_slice(rest);
        buf
    }

    fn drain(&mut self, cx: &mut Context<'_>) -> Poll<io::Result<()>> {
        let Some(pending) = self.pending.take() else {
            return Poll::Ready(Ok(()));
        };
        let result = loop {
            if self.pending_written >= pending.len() {
                break Ok(());
            }
            let rest = pending.get(self.pending_written..).unwrap_or_default();
            let poll = Pin::new(&mut *self.conn).poll_write(cx, rest);
            match poll {
                Poll::Pending => {
                    self.pending = Some(pending);
                    return Poll::Pending;
                }
                Poll::Ready(Err(err)) => break Err(err),
                Poll::Ready(Ok(0)) => break Err(io::ErrorKind::WriteZero.into()),
                Poll::Ready(Ok(n)) => self.pending_written += n,
            }
        };
        self.pending_written = 0;
        pool::put_buffer(pending);
        Poll::Ready(result)
    }
}

impl AsyncRead for HttpConn {
    fn poll_read(self: Pin<&mut Self>, cx: &mut Context<'_>, buf: &mut ReadBuf<'_>) -> Poll<io::Result<()>> {
        let this = self.get_mut();

        if !this.buf.is_empty() {
            let n = buf.remaining().min(this.buf.len());
            buf.put_slice(this.buf.get(..n).unwrap_or_default());
            if n == this.buf.len() {
                this.buf.clear();
            } else {
                this.buf.drain(..n);
            }
            return Poll::Ready(Ok(()));
        }

        if this.has_recv_header {
            return Pin::new(&mut *this.conn).poll_read(cx, buf);
        }

        let mut scratch = pool::get(pool::RELAY_BUFFER_SIZE);
        let poll = {
            let mut read_buf = ReadBuf::new(&mut scratch);
            match Pin::new(&mut *this.conn).poll_read(cx, &mut read_buf) {
                Poll::Pending => Poll::Pending,
                Poll::Ready(Err(err)) => Poll::Ready(Err(err)),
                Poll::Ready(Ok(())) => Poll::Ready(Ok(read_buf.filled().len())),
            }
        };
        let n = match poll {
            Poll::Pending => {
                pool::put(scratch).ok();
                return Poll::Pending;
            }
            Poll::Ready(Err(err)) => {
                pool::put(scratch).ok();
                return Poll::Ready(Err(err));
            }
            Poll::Ready(Ok(n)) => n,
        };

        let Some(pos) = index_of(scratch.get(..n).unwrap_or_default(), b"\r\n\r\n") else {
            pool::put(scratch).ok();
            return Poll::Ready(Ok(()));
        };
        this.has_recv_header = true;
        let data_length = n - pos - 4;
        let copied = buf.remaining().min(data_length);
        let start = 4 + pos;
        buf.put_slice(scratch.get(start..start + copied).unwrap_or_default());
        if data_length > copied {
            this.buf.extend_from_slice(scratch.get(start + copied..start + data_length).unwrap_or_default());
        }
        pool::put(scratch).ok();
        Poll::Ready(Ok(()))
    }
}

impl AsyncWrite for HttpConn {
    fn poll_write(self: Pin<&mut Self>, cx: &mut Context<'_>, buf: &[u8]) -> Poll<io::Result<usize>> {
        let this = self.get_mut();

        if this.pending.is_none() {
            if this.has_sent_header {
                return Pin::new(&mut *this.conn).poll_write(cx, buf);
            }
            let head = this.build_head(buf);
            this.pending = Some(head);
            this.pending_written = 0;
        }

        match this.drain(cx) {
            Poll::Pending => Poll::Pending,
            Poll::Ready(Err(err)) => Poll::Ready(Err(err)),
            Poll::Ready(Ok(())) => {
                this.has_sent_header = true;
                Poll::Ready(Ok(buf.len()))
            }
        }
    }

    fn poll_flush(self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<io::Result<()>> {
        let this = self.get_mut();
        match this.drain(cx) {
            Poll::Pending => Poll::Pending,
            Poll::Ready(Err(err)) => Poll::Ready(Err(err)),
            Poll::Ready(Ok(())) => Pin::new(&mut *this.conn).poll_flush(cx),
        }
    }

    fn poll_shutdown(self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<io::Result<()>> {
        Pin::new(&mut *self.get_mut().conn).poll_shutdown(cx)
    }
}

impl Stream for HttpConn {
    fn local_addr(&self) -> io::Result<std::net::SocketAddr> {
        self.conn.local_addr()
    }

    fn peer_addr(&self) -> io::Result<std::net::SocketAddr> {
        self.conn.peer_addr()
    }

    fn shutdown_read(&self) -> io::Result<()> {
        self.conn.shutdown_read()
    }

    fn shutdown_write(&self) -> io::Result<()> {
        self.conn.shutdown_write()
    }

    fn old_conn(&self) -> Option<&dyn murmur_std_compat::net::Conn> {
        self.conn.old_conn()
    }
}

fn index_of(haystack: &[u8], needle: &[u8]) -> Option<usize> {
    haystack.windows(needle.len()).position(|window| window == needle)
}

fn pack_url_encoded_head_data(buf: &mut BytesMut, data: &[u8]) {
    for &byte in data {
        buf.put_u8(b'%');
        for nibble in [byte >> 4, byte & 0xf] {
            buf.put_u8(hex_digit(nibble));
        }
    }
}

/// One lowercase hex digit.
fn hex_digit(nibble: u8) -> u8 {
    if nibble < 10 {
        b'0' + nibble
    } else {
        b'a' + nibble - 10
    }
}

fn pack_boundary(buf: &mut BytesMut) {
    const SET: &[u8; 62] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
    buf.put_slice(b"Content-Type: multipart/form-data; boundary=");
    for _ in 0..32 {
        if let Some(byte) = SET.get(rand::rng().random_range(0..SET.len())) {
            buf.put_u8(*byte);
        }
    }
    buf.put_slice(b"\r\n");
}

