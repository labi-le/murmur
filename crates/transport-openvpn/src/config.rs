//! Connection configuration: ciphers, auth digests and the negotiated option set.

use std::collections::HashMap;

use anyhow::{bail, Result};

use super::tlscrypt_v2::{decode_tls_crypt_v2_client_key, pem_decode};
use murmur_common::time::TimeDuration;

pub const PROTO_UDP: &str = "udp";
pub const PROTO_TCP: &str = "tcp";

pub const CIPHER_AES_128_GCM: &str = "AES-128-GCM";
pub const CIPHER_AES_192_GCM: &str = "AES-192-GCM";
pub const CIPHER_AES_256_GCM: &str = "AES-256-GCM";
pub const CIPHER_AES_CBC: &str = "AES-CBC";
pub const CIPHER_AES_128_CBC: &str = "AES-128-CBC";
pub const CIPHER_AES_192_CBC: &str = "AES-192-CBC";
pub const CIPHER_AES_256_CBC: &str = "AES-256-CBC";
pub const CIPHER_CHACHA20_POLY1305: &str = "CHACHA20-POLY1305";
pub const AUTH_MD5: &str = "MD5";
pub const AUTH_SHA1: &str = "SHA1";
pub const AUTH_SHA256: &str = "SHA256";
pub const AUTH_SHA384: &str = "SHA384";
pub const AUTH_SHA512: &str = "SHA512";

pub const COMP_LZO_YES: &str = "yes";

/// The normalized subset generated by hwdsl2/openvpn-install.
#[derive(Clone, Debug, Default)]
pub struct ClientConfig {
    pub remote_host: String,
    pub remote_port: u16,
    pub proto: String,
    pub dev: String,
    pub cipher: String,
    pub auth: String,
    pub comp_lzo: String,

    pub ca: Vec<u8>,
    pub cert: Vec<u8>,
    pub key: Vec<u8>,
    pub tls_auth: Vec<u8>,
    pub tls_crypt: Vec<u8>,

    pub key_direction: String,

    pub username: String,
    pub password: String,

    pub peer_info: HashMap<String, String>,

    pub ping_interval: TimeDuration,
    pub ping_restart: TimeDuration,
    pub transition_window: TimeDuration,
    pub transition_window_set: bool,

    pub tls_crypt_key: Vec<u8>,
    pub tls_auth_key: Vec<u8>,

    /// The first 256 bytes of tls-crypt-v2 client key material.
    pub tls_crypt_v2_key: Vec<u8>,
    /// Appended to the initial V3 hard-reset packet.
    pub tls_crypt_v2_wrapped_key: Vec<u8>,
    /// The raw PEM-encoded `OpenVPN` tls-crypt-v2 client key.
    pub tls_crypt_v2: Vec<u8>,

    /// Data channel ciphers the client offers to the server for negotiation
    /// (`OpenVPN` `--data-ciphers`). If non-empty, the negotiated cipher is the
    /// first entry in the server's pushed cipher list that also appears here.
    /// If empty, the single `Cipher` field is used.
    pub data_ciphers: Vec<String>,

    /// Used when the server does not support cipher negotiation
    /// (`OpenVPN` `--data-ciphers-fallback`).
    pub fallback_cipher: String,
}

impl ClientConfig {
    /// The key size for the negotiated data cipher.
    #[must_use]
    pub fn data_cipher_key_length(&self) -> usize {
        cipher_key_length(&self.cipher)
    }

    /// Selects the data channel cipher based on the server-pushed cipher list
    /// and the locally configured `data_ciphers` list.
    ///
    /// If the server pushed a cipher list (via "data-ciphers" or "cipher" push
    /// options), the result is the first cipher in the server's list that also
    /// appears in the local `data_ciphers` list. If no intersection exists and
    /// a `fallback_cipher` is configured, it is used. If no fallback is
    /// configured but the server pushed a single cipher that matches the local
    /// `cipher`, that is used.
    ///
    /// If the server did not push any cipher options, the local `cipher` is
    /// used as-is (legacy behavior for servers without cipher negotiation).
    pub fn negotiate_cipher(&self, pushed_ciphers: &[String], pushed_cipher: &str) -> Result<String> {
        if pushed_ciphers.is_empty() && pushed_cipher.is_empty() {
            return Ok(self.cipher.clone());
        }

        if !self.data_ciphers.is_empty() {
            let mut server_list = pushed_ciphers.to_vec();
            if server_list.is_empty() && !pushed_cipher.is_empty() {
                server_list = vec![pushed_cipher.to_owned()];
            }
            for server_cipher in &server_list {
                let normalized = normalize_cipher(server_cipher);
                for local_cipher in &self.data_ciphers {
                    if normalize_cipher(local_cipher) == normalized {
                        return Ok(normalized);
                    }
                }
            }
            if !self.fallback_cipher.is_empty() {
                return Ok(normalize_cipher(&self.fallback_cipher));
            }
            bail!(
                "no common data cipher between client {} and server {}",
                join_string_slice(&self.data_ciphers),
                join_string_slice(&server_list)
            );
        }

        if !pushed_cipher.is_empty() {
            let normalized = normalize_cipher(pushed_cipher);
            if normalized == self.cipher {
                return Ok(normalized);
            }
            if !self.fallback_cipher.is_empty() {
                return Ok(normalize_cipher(&self.fallback_cipher));
            }
            if is_supported_cipher(&normalized) {
                return Ok(normalized);
            }
            bail!("server pushed unsupported cipher {pushed_cipher:?}");
        }

        if !pushed_ciphers.is_empty() {
            for sc in pushed_ciphers {
                let normalized = normalize_cipher(sc);
                if is_supported_cipher(&normalized) {
                    if !self.fallback_cipher.is_empty() {
                        return Ok(normalize_cipher(&self.fallback_cipher));
                    }
                    return Ok(normalized);
                }
            }
        }

        Ok(self.cipher.clone())
    }

    #[must_use]
    pub fn remote_address(&self) -> String {
        join_host_port(&self.remote_host, self.remote_port)
    }

    pub fn prepare(&mut self) -> Result<()> {
        self.remote_host = self.remote_host.trim().to_owned();
        self.proto = normalize_proto(&self.proto);
        if self.dev.is_empty() {
            "tun".clone_into(&mut self.dev);
        }
        self.dev = self.dev.trim().to_lowercase();
        self.cipher = normalize_cipher(&self.cipher);
        self.auth = normalize_auth(&self.auth);
        self.comp_lzo = normalize_comp_lzo(&self.comp_lzo);

        self.validate_install_script_subset()?;
        if !bytes_trim_space(&self.tls_auth).is_empty() {
            let key = decode_static_key(&self.tls_auth).map_err(|err| anyhow::anyhow!("parse tls-auth key: {err}"))?;
            self.tls_auth_key = key;
        }
        if !bytes_trim_space(&self.tls_crypt).is_empty() {
            let key =
                decode_static_key(&self.tls_crypt).map_err(|err| anyhow::anyhow!("parse tls-crypt key: {err}"))?;
            self.tls_crypt_key = key;
        }
        if !bytes_trim_space(&self.tls_crypt_v2).is_empty() {
            let (key_material, wrapped_key) = decode_tls_crypt_v2_client_key(&self.tls_crypt_v2)
                .map_err(|err| anyhow::anyhow!("parse tls-crypt-v2 client key: {err}"))?;
            self.tls_crypt_v2_key = key_material;
            self.tls_crypt_v2_wrapped_key = wrapped_key;
        }
        Ok(())
    }

    pub fn validate_install_script_subset(&self) -> Result<()> {
        if self.remote_host.is_empty() || self.remote_port == 0 {
            bail!("openvpn config requires remote host and port");
        }
        if self.dev != "tun" {
            bail!("unsupported openvpn dev {:?}: only dev tun is supported", self.dev);
        }
        if self.proto != PROTO_UDP && self.proto != PROTO_TCP {
            bail!("unsupported openvpn proto {:?}: only udp and tcp are supported", self.proto);
        }
        if self.cipher != CIPHER_AES_128_GCM
            && self.cipher != CIPHER_AES_192_GCM
            && self.cipher != CIPHER_AES_256_GCM
            && self.cipher != CIPHER_AES_128_CBC
            && self.cipher != CIPHER_AES_192_CBC
            && self.cipher != CIPHER_AES_256_CBC
            && self.cipher != CIPHER_CHACHA20_POLY1305
        {
            bail!(
                "unsupported openvpn cipher {:?}: only {}, {}, {}, {}, {}, {} and {} are supported",
                self.cipher,
                CIPHER_AES_128_GCM,
                CIPHER_AES_192_GCM,
                CIPHER_AES_256_GCM,
                CIPHER_AES_128_CBC,
                CIPHER_AES_192_CBC,
                CIPHER_AES_256_CBC,
                CIPHER_CHACHA20_POLY1305
            );
        }
        if self.auth != AUTH_MD5
            && self.auth != AUTH_SHA1
            && self.auth != AUTH_SHA256
            && self.auth != AUTH_SHA384
            && self.auth != AUTH_SHA512
        {
            bail!(
                "unsupported openvpn auth {:?}: only {}, {}, {}, {} and {} are supported",
                self.auth,
                AUTH_MD5,
                AUTH_SHA1,
                AUTH_SHA256,
                AUTH_SHA384,
                AUTH_SHA512
            );
        }
        if self.key_direction != "1" && self.key_direction != "0" && !self.key_direction.is_empty() {
            bail!("unsupported openvpn key-direction {:?}: only '1' and '0' are supported", self.key_direction);
        }
        if !bytes_trim_space(&self.tls_auth).is_empty() && !bytes_trim_space(&self.tls_crypt).is_empty() {
            bail!("openvpn tls-auth and tls-crypt are mutually exclusive");
        }
        if !bytes_trim_space(&self.tls_crypt_v2).is_empty()
            && (!bytes_trim_space(&self.tls_auth).is_empty() || !bytes_trim_space(&self.tls_crypt).is_empty())
        {
            bail!("openvpn tls-crypt-v2 is mutually exclusive with tls-auth and tls-crypt");
        }
        if bytes_trim_space(&self.ca).is_empty() {
            bail!("openvpn config requires inline <ca> block");
        }
        if pem_decode(&self.ca).is_none() {
            bail!("inline <ca> block is not PEM");
        }
        let has_cert = !bytes_trim_space(&self.cert).is_empty() || !bytes_trim_space(&self.key).is_empty();
        if has_cert {
            if bytes_trim_space(&self.cert).is_empty() || bytes_trim_space(&self.key).is_empty() {
                bail!("openvpn cert and key must both be set when using client certificate auth");
            }
            if pem_decode(&self.cert).is_none() {
                bail!("inline <cert> block is not PEM");
            }
            if pem_decode(&self.key).is_none() {
                bail!("inline <key> block is not PEM");
            }
        } else if self.username.trim().is_empty() {
            bail!("openvpn requires either cert+key or username (auth-user-pass)");
        }
        if self.ping_interval < 0 {
            bail!("openvpn ping interval must be positive");
        }
        if self.ping_restart < 0 {
            bail!("openvpn ping restart must be positive");
        }
        if self.transition_window < 0 {
            bail!("openvpn transition window must be non-negative");
        }
        Ok(())
    }
}

/// The key size for a given cipher name.
#[must_use]
pub fn cipher_key_length(cipher: &str) -> usize {
    match cipher {
        CIPHER_AES_256_GCM | CIPHER_AES_256_CBC | CIPHER_CHACHA20_POLY1305 => 32,
        CIPHER_AES_192_GCM | CIPHER_AES_192_CBC => 24,
        _ => 16,
    }
}

/// True if the cipher name is recognized.
pub(crate) fn is_supported_cipher(cipher: &str) -> bool {
    matches!(
        cipher,
        CIPHER_AES_128_GCM
            | CIPHER_AES_192_GCM
            | CIPHER_AES_256_GCM
            | CIPHER_AES_128_CBC
            | CIPHER_AES_192_CBC
            | CIPHER_AES_256_CBC
            | CIPHER_CHACHA20_POLY1305
    )
}

pub(crate) fn normalize_proto(proto: &str) -> String {
    match proto.trim().to_lowercase().as_str() {
        "" | "udp" | "udp4" => PROTO_UDP.to_owned(),
        "tcp" | "tcp-client" | "tcp4" | "tcp4-client" => PROTO_TCP.to_owned(),
        _ => proto.trim().to_lowercase(),
    }
}

pub(crate) fn normalize_cipher(cipher: &str) -> String {
    match cipher.trim().to_uppercase().as_str() {
        "" => CIPHER_AES_128_GCM.to_owned(),
        CIPHER_AES_CBC => CIPHER_AES_128_CBC.to_owned(),
        _ => cipher.trim().to_uppercase(),
    }
}

pub(crate) fn normalize_auth(auth: &str) -> String {
    match auth.trim().to_uppercase().as_str() {
        "" => AUTH_SHA256.to_owned(),
        "SHA-1" => AUTH_SHA1.to_owned(),
        _ => auth.trim().to_uppercase(),
    }
}

pub(crate) fn normalize_comp_lzo(comp_lzo: &str) -> String {
    match comp_lzo.trim().to_lowercase().as_str() {
        "yes" | "adaptive" => COMP_LZO_YES.to_owned(),
        _ => comp_lzo.trim().to_lowercase(),
    }
}

/// Parses the hex-body "`OpenVPN` Static key V1" block used for tls-auth,
/// tls-crypt and tls-crypt-v2 key material.
pub fn decode_static_key(block: &[u8]) -> Result<Vec<u8>> {
    let text = String::from_utf8_lossy(block);
    let mut hex_lines: Vec<String> = Vec::new();
    for raw in text.split('\n') {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if line.starts_with("-----BEGIN OpenVPN Static key") || line.starts_with("-----END OpenVPN Static key") {
            continue;
        }
        hex_lines.push(line.to_owned());
    }
    let encoded = hex_lines.concat();
    let key = hex::decode(encoded)?;
    if key.len() != 256 {
        bail!("invalid static key length {}, expected 256 bytes", key.len());
    }
    Ok(key)
}

/// Trims Unicode whitespace from both ends while
/// keeping the argument's bytes untouched when it is not UTF-8.
fn bytes_trim_space(input: &[u8]) -> &[u8] {
    match std::str::from_utf8(input) {
        Ok(text) => text.trim().as_bytes(),
        Err(_) => input.trim_ascii(),
    }
}

/// Joins a host and port: a literal IPv6 host is bracketed.
fn join_host_port(host: &str, port: u16) -> String {
    if host.contains(':') {
        format!("[{host}]:{port}")
    } else {
        format!("{host}:{port}")
    }
}

/// Render a string list as `[a b c]` for an error message.
fn join_string_slice(list: &[String]) -> String {
    format!("[{}]", list.join(" "))
}
